# Desk 1: centralized (orchestrator whose tools are the experts) with a step limit
# ----------------------------------------------------------------------------------------
def centralized(message: str, step_limit: int = 9, together: bool = False, boss_does_sum: bool = False) -> dict:
    """The orchestrator is a create_agent agent whose three tools are ask_stays_expert, ask_policy_expert and
    ask_general_expert. Each tool call runs a whole expert agent. One step = one model call or one round of tool runs."""
    run, parts = Run(), split_parts(message)
    k = len(parts)
    # orchestrator plan: k tool calls, either one per step or all in one step, then a final answer
    if together:
        rounds = [parts]
    else:
        rounds = [[p] for p in parts]
    refund_part = next((p for p in parts if p["expert"] == "policy" and booking_details(p["part"])["days"] is not None
                        and booking_details(p["part"])["stay"] and booking_details(p["part"])["nights"]), None)
    if boss_does_sum and refund_part:
        # the boss notices the policy expert lacks the price, asks the stays expert in an extra step, then does the sum itself
        rounds = rounds + [[{"expert": "stays", "part": "price per night of " + booking_details(refund_part["part"])["stay"],
                             "extra": True}]]
    steps_needed = 2 * len(rounds) + 1               # model, tools, model, tools, ..., model
    allowed = step_limit - 1                          # measured: a run of S steps needs recursion_limit >= S + 1
    steps, answers = 0, []
    run.event("customer", "orchestrator", "message", message)
    for rnd in rounds:
        if steps + 1 > allowed:
            break
        steps += 1
        run.calls += 1                                # the orchestrator's model call that requests these tools
        if steps + 1 > allowed:
            break
        steps += 1                                    # the tools node runs every requested tool
        for p in rnd:
            run.say("boss -> %s: %s" % (EXPERT_NAME[p["expert"]], p["part"]), 0)
            run.event("orchestrator", EXPERT_NAME[p["expert"]], "tool call (agent as tool)", p["part"])
            ans = expert_answer(run, p["expert"], p["part"])
            run.event(EXPERT_NAME[p["expert"]], "orchestrator", "tool result", ans)
            answers.append((p, ans))
    if steps + 1 > allowed or steps < 2 * len(rounds):
        run.error = ("GraphRecursionError: Recursion limit of %d reached without hitting a stop condition. "
                     "(This plan needs %d steps, so recursion_limit must be at least %d.)" % (step_limit, steps_needed, steps_needed + 1))
        return {"run": run, "answer": "", "parts": parts, "steps_needed": steps_needed, "steps_run": steps,
                "score": score(""), "stopped": True}
    run.calls += 1                                    # final model call: the orchestrator writes the reply
    steps += 1
    texts = [a for p, a in answers if not p.get("extra")]
    reply = " ".join(texts)
    extra = [a for p, a in answers if p.get("extra")]
    if extra:
        b = booking_details(refund_part["part"])
        price = stays[b["stay"]]["price_per_night"]
        refund = price * b["nights"] * refund_percent(b["days"]) / 100
        reply += " (The boss worked out the amount itself: Rs %s × %d nights × %d%% = about Rs %s.)" % (
            "{:,}".format(price), b["nights"], refund_percent(b["days"]), "{:,.0f}".format(refund))
    run.event("orchestrator", "customer", "reply", reply)
    return {"run": run, "answer": reply, "parts": parts, "steps_needed": steps_needed, "steps_run": steps,
            "score": score(reply), "stopped": False, "boss_math": bool(extra)}


# ----------------------------------------------------------------------------------------
# Desk 2: decentralized ("is this mine?" for each peer, in order)
# ----------------------------------------------------------------------------------------
PEER_ORDER = ["stays", "policy", "general"]
PEER_LABEL = {"stays": "Stays expert", "policy": "Policy expert", "general": "General expert"}


def decentralized(message: str, approach: str = "notebook", order: list | None = None) -> dict:
    """approach='notebook': the first expert that says 'mine' answers the whole message (the notebook's loop).
    approach='relay': approach 3 (homework): each expert answers only its own part and passes the REST on."""
    run, parts = Run(), split_parts(message)
    order = order or PEER_ORDER
    run.event("customer", PEER_LABEL[order[0]], "message", message)
    answers, remaining = [], list(parts)
    for i, key in enumerate(order):
        mine = [p for p in remaining if p["expert"] == key]
        last = i == len(order) - 1
        if last:
            if approach == "relay":
                if mine:
                    run.say("%s: last in line; I'll answer my part and send the combined reply." % PEER_LABEL[key])
                    answers.append(expert_answer(run, key, " ".join(p["part"] for p in mine)))
                    remaining = [p for p in remaining if p not in mine]
                else:
                    run.say("%s: last in line; nothing of mine is left, I'll send the combined reply." % PEER_LABEL[key])
                    run.calls += 1
            else:
                run.say("%s: last resort, I'll answer." % PEER_LABEL[key])
                answers.append(expert_answer(run, key, message))
            run.event(PEER_LABEL[key], "customer", "reply", " ".join(answers))
            break
        run.calls += 1                                   # the structured "is this mine?" decision
        if mine:
            reason = "this message asks about %s, which is my area" % ("a stay's price" if key == "stays" else "a cancellation refund" if key == "policy" else "a greeting")
            run.say("%s: mine (%s)" % (PEER_LABEL[key], reason))
            run.event(PEER_LABEL[key], PEER_LABEL[key], "decision", "handle_it=True: " + reason)
            if approach == "relay":
                answers.append(expert_answer(run, key, " ".join(p["part"] for p in mine)))
                remaining = [p for p in remaining if p not in mine]
                rest = " ".join(p["part"] for p in remaining) or "(nothing left)"
                nxt = PEER_LABEL[order[i + 1]]
                run.say("%s: answered my part, passing the rest to %s: %s" % (PEER_LABEL[key], nxt, rest[:80]))
                run.event(PEER_LABEL[key], nxt, "pass the rest on", rest)
                continue
            answers.append(expert_answer(run, key, message))
            run.event(PEER_LABEL[key], "customer", "reply", answers[-1])
            break
        reason = "nothing here is about %s" % ("stays or prices" if key == "stays" else "cancellations or refunds")
        run.say("%s: not mine (%s), passing it on" % (PEER_LABEL[key], reason))
        run.event(PEER_LABEL[key], PEER_LABEL[order[i + 1]], "pass it on", "handle_it=False: " + reason)
    reply = " ".join(answers)
    answered = {p["expert"] for p in parts} if approach == "relay" else (
        {p["expert"] for p in parts if p["expert"] == next((k for k in order if any(q["expert"] == k for q in parts)), "general")})
    return {"run": run, "answer": reply, "parts": parts, "score": score(reply), "answered_owners": answered}


# ----------------------------------------------------------------------------------------
# Desk 3: hybrid (light router + experts who talk to each other)
# ----------------------------------------------------------------------------------------
def hybrid(message: str, peer_talk: bool = True) -> dict:
    run, parts = Run(), split_parts(message)
    run.calls += 1                                       # the router: one structured-output call that only splits
    run.event("customer", "router", "message", message)
    run.event("router", "router", "routing (structured output)", json.dumps({"parts": parts})[:140])
    answers = []
    for item in parts:
        run.say("router -> %s expert: %s" % (item["expert"], item["part"]))
        run.event("router", EXPERT_NAME[item["expert"]], "part", item["part"])
        ans = expert_answer(run, item["expert"], item["part"], can_ask_peer=peer_talk)
        answers.append("[%s] %s" % (item["expert"], ans))
    run.calls += 1                                       # combine everything into one reply
    reply = " ".join(a.split("] ", 1)[1] for a in answers)
    run.event("combine step", "customer", "reply", reply)
    return {"run": run, "answer": reply, "parts": parts, "score": score(reply), "expert_answers": answers}


def scoreboard(message: str = MULTI_PART, step_limit: int = 9) -> list:
    rows = []
    for name, fn in (("Centralized", lambda: centralized(message, step_limit)),
                     ("Decentralized", lambda: decentralized(message)),
                     ("Hybrid", lambda: hybrid(message))):
        r = fn()
        rows.append({"Desk": name, "Greeting?": r["score"]["greeting"], "Price Rs 3,200?": r["score"]["price"],
                     "Refund Rs 3,600?": r["score"]["refund"], "Model calls": r["run"].calls,
                     "_answer": r["answer"] or r["run"].error})
    return rows



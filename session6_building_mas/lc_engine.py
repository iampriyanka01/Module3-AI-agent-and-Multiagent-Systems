# Understanding a message: which parts does it have, and who owns each part?
# ----------------------------------------------------------------------------------------
GREETING = ("hi", "hello", "hey", "how are you", "good morning", "namaste", "thanks", "thank you")
POLICY_WORDS = ("cancel", "refund", "money back", "get back", "policy", "change our date", "change the date", "reschedul")
STAY_WORDS = ("price", "per night", "cost", "stays", "stay ", "cottage", "homestay", "where can we stay", "old manali", "coorg")


def split_parts(message: str) -> list:
    """Split a message into sentences and label each with the expert who owns it (what the router does in the notebook).
    Policy words win over stay words, so 'cancellation policy for homestays' is a policy question (the homework's trap)."""
    pieces = [p.strip() for p in re.split(r"(?<=[?.!])\s+", message) if p.strip()]
    parts = []
    for p in pieces:
        low = " " + p.lower() + " "
        if any(w in low for w in POLICY_WORDS):
            owner = "policy"
        elif any(w in low for w in STAY_WORDS):
            owner = "stays"
        elif any(re.search(r"\b" + re.escape(w) + r"\b", low) for w in GREETING):
            owner = "general"
        else:
            continue                     # filler such as "i have a couple of questions"
        if parts and parts[-1]["expert"] == owner:
            parts[-1]["part"] += " " + p
        else:
            parts.append({"expert": owner, "part": p})
    return parts or [{"expert": "general", "part": message}]


def find_stay(text: str) -> str:
    low = text.lower()
    for name in stays:
        if name.lower() in low or name.split()[0].lower() + " " + name.split()[1].lower() in low:
            return name
    return ""


def booking_details(text: str) -> dict:
    nights = re.search(r"(\d+)[- ]night", text.lower())
    days = re.search(r"(\d+)\s*days?\s*before", text.lower())
    return {"stay": find_stay(text), "nights": int(nights.group(1)) if nights else None,
            "days": int(days.group(1)) if days else None}


# ----------------------------------------------------------------------------------------
# A run: everything that happened, in the notebook's print style, plus counts
# ----------------------------------------------------------------------------------------
class Run:
    def __init__(self):
        self.lines: list = []          # (indent, text): what the notebook prints
        self.calls = 0                 # model calls (every AI message, plus structured-output calls)
        self.events: list = []         # (who, to, kind, text) for a message log
        self.error = ""

    def say(self, text: str, indent: int = 0):
        self.lines.append(("   " * indent) + text)

    def event(self, who, to, kind, text):
        self.events.append({"from": who, "to": to, "kind": kind, "content": text[:140]})

    def printed(self) -> str:
        return "\n".join(self.lines)


EXPERT_NAME = {"stays": "stays expert", "policy": "policy expert", "general": "general expert"}


def expert_answer(run: Run, expert: str, text: str, can_ask_peer: bool = False, indent: int = 2,
                  show_tools: bool = True) -> str:
    """One expert = one create_agent agent. Returns its answer and counts its model calls exactly as ask() does:
    every AI message is one call (a tool-calling message, then a final answer)."""
    name = EXPERT_NAME[expert]
    if expert == "general":
        run.calls += 1                                     # no tools: one AI message
        return "Hello! We're doing well, thank you for asking, and we're happy to help with your questions."

    if expert == "stays":
        stay = find_stay(text)
        query = stay or ("Old Manali" if "manali" in text.lower() else "Coorg" if "coorg" in text.lower() else "all")
        result = search_stays(query)
        run.calls += 2                                     # AI(tool call) + AI(final answer)
        if show_tools:
            run.say("[stays expert] used search_stays({'query': '%s'})" % query, indent)
        run.event("stays expert", "search_stays", "tool", result)
        if stay:
            s = stays[stay]
            return "%s in %s costs Rs %s per night; it is %s." % (stay, s["place"], "{:,}".format(s["price_per_night"]), s["notes"])
        return "Here is what we have: " + result.replace("\n", "; ")

    # policy expert
    rule = look_up_policy("cancellation" if any(w in text.lower() for w in ("cancel", "refund", "back")) else "changes")
    calls = 1                                              # AI(tool call)
    used = [("look_up_policy({'topic': 'cancellation'})", rule)]
    b = booking_details(text)
    if b["days"] is None:                                   # a general policy question
        calls += 1
        for call, res in used:
            if show_tools:
                run.say("[policy expert] used " + call, indent)
            run.event("policy expert", "look_up_policy", "tool", res)
        run.calls += calls
        return "Our cancellation policy: " + rule
    pct = refund_percent(b["days"])
    if can_ask_peer and b["stay"] and b["nights"]:
        calls += 1                                         # AI(asks the stays peer)
        q = "price per night of " + b["stay"]
        run.say("policy expert -> stays expert: " + q, indent)
        run.event("policy expert", "stays expert", "peer question (direct)", q)
        peer_answer = expert_answer(run, "stays", q, indent=indent + 1, show_tools=show_tools)   # +2 calls inside
        run.event("stays expert", "policy expert", "peer answer (direct)", peer_answer)
        price = stays[b["stay"]]["price_per_night"]
        calc = calculate_refund(price, b["nights"], b["days"])
        calls += 1                                         # AI(calls calculate_refund)
        calls += 1                                         # AI(final answer)
        used += [("ask_stays_peer({'question': '%s'})" % q, peer_answer),
                 ("calculate_refund({'price_per_night': %d, 'nights': %d, 'days_before_check_in': %d})" % (price, b["nights"], b["days"]), calc)]
        for call, res in used:
            if show_tools:
                run.say("[policy expert] used " + call, indent)       # printed after its peer chat, as in the notebook
        run.event("policy expert", "calculate_refund", "tool (code does the maths)", calc)
        run.calls += calls
        refund = price * b["nights"] * pct / 100
        return ("Cancelling %d days before check-in gives %d%% back. You paid Rs %s for %d nights at %s, so you get "
                "Rs %s back." % (b["days"], pct, "{:,}".format(price * b["nights"]), b["nights"], b["stay"], "{:,.0f}".format(refund)))
    calls += 1                                             # AI(final answer) without the price
    for call, res in used:
        if show_tools:
            run.say("[policy expert] used " + call, indent)
        run.event("policy expert", "look_up_policy", "tool", res)
    run.calls += calls
    return ("Cancelling %d days before check-in falls in our %s window, so you get %d%% of what you paid back. "
            "I don't know what you paid for this booking, so I can't give the exact amount."
            % (b["days"], "7 or more days" if pct == 80 else "2 to 6 days" if pct == 50 else "less than 2 days", pct))


def score(answer: str) -> dict:
    return {"price": any(x in answer for x in EXPECTED["price"]), "refund": any(x in answer for x in EXPECTED["refund"]),
            "greeting": bool(re.search(r"\b(hello|hi|doing well)\b", answer.lower()))}


